using Content.Client.UserInterface.Controls;
using Content.Shared._Impstation.PersonalEconomy.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Impstation.PersonalEconomy.UI;

[GenerateTypedNameReferences]
public sealed partial class ATMMenu : FancyWindow
{
    public Action? OnTransactionButtonPressed;
    public Action? OnInsertCardPressed;
    public Action? OnEjectCardPressed;
    public Action? OnDepositPressed;
    public Action<int>? OnWithdrawPressed;

    private NoAccountInfoBox? _noAccountBox;
    private AccountInfoBox? _accountBox;

    public ATMMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        CreateInvalidInfoBox();
    }

    public void UpdateState(Entity<BankAccountComponent>? account, bool cardInserted, StationPayrollComponent? payroll)
    {
        if (account == null)
        {
            if (_noAccountBox == null)
                CreateInvalidInfoBox();

            _noAccountBox?.SetUnprogrammed(cardInserted);
            return;
        }

        if (_accountBox?.Account.Owner != account.Value.Owner)
            CreateInfoBoxForAccount(account.Value);

        _accountBox?.UpdateState(payroll);
    }

    public void CreateInvalidInfoBox()
    {
        ClearInfoBox();

        _noAccountBox = new NoAccountInfoBox();
        _noAccountBox.OnInsertCardPressed += () => OnInsertCardPressed?.Invoke();
        _noAccountBox.OnEjectCardPressed += () => OnEjectCardPressed?.Invoke();
        AccountInfoContainer.AddChild(_noAccountBox);
    }

    public void CreateInfoBoxForAccount(Entity<BankAccountComponent> account)
    {
        ClearInfoBox();

        _accountBox = new AccountInfoBox(account);
        _accountBox.OnTransactionButtonPressed += () => OnTransactionButtonPressed?.Invoke();
        _accountBox.OnEjectPressed += () => OnEjectCardPressed?.Invoke();
        _accountBox.OnDepositPressed += () => OnDepositPressed?.Invoke();
        _accountBox.OnWithdrawPressed += amount => OnWithdrawPressed?.Invoke(amount);
        AccountInfoContainer.AddChild(_accountBox);
    }

    public void ClearInfoBox()
    {
        AccountInfoContainer.RemoveAllChildren();
        _accountBox = null;
        _noAccountBox = null;
    }
}
